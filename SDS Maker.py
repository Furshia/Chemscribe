def identify_phase(chemical: str) -> tuple[str, str]: #AI Function
    phase_match = re.search(
        r'\((gas|g|liquid|l|solid|s)\)',
        chemical,
        re.IGNORECASE
    )

    if phase_match:
        phase = {
            'g': 'gas',
            'gas': 'gas',
            'l': 'liquid',
            'liquid': 'liquid',
            's': 'solid',
            'solid': 'solid'
        }[phase_match.group(1).lower()]

        chemical = re.sub(
            r'\s*\((?:gas|g|liquid|l|solid|s)\)\s*',
            '',
            chemical,
            flags=re.IGNORECASE
        ).strip()

    else:
        phase = 'aqueous'

    return chemical, phase


